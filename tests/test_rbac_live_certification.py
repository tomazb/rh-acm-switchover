class TestLiveValidateAllPermissions:
    """Run the full RBACValidator.validate_all_permissions() in SSAR mode."""

    def test_all_required_permissions_pass(self, rbac_validator):
        """validate_all_permissions() must report no errors for a correctly bound operator SA."""
        all_valid, errors = rbac_validator.validate_all_permissions(
            include_decommission=False,
            skip_observability=False,
        )
        flat_errors = [msg for msgs in errors.values() for msg in msgs]
        assert all_valid, f"RBAC validation failed with {len(flat_errors)} error(s):\n" + "\n".join(flat_errors)

    def test_decommission_permissions_pass_when_bound(self, rbac_validator):
        """With decommission ClusterRole bound, validate_cluster_permissions(include_decommission=True) must pass."""
        all_valid, errors = rbac_validator.validate_cluster_permissions(
            include_decommission=True,
            skip_observability=False,
        )
        assert all_valid, f"Decommission RBAC validation failed:\n" + "\n".join(errors)
