"""
Live RBAC certification tests.

These tests validate that the permissions defined in the RBAC manifests are
actually granted end-to-end on a live (or disposable) cluster.  They use
SelfSubjectAccessReview (SSAR) so they are non-mutating: no resources are
created or deleted.  The current kubeconfig user (or service account) must
already have the documented RBAC applied before these tests are run.

Gating
------
Tests are skipped unless the ``ACM_ENABLE_LIVE_RBAC_CERTIFICATION=1``
environment variable is set.  Set ``ACM_LIVE_RBAC_CONTEXT`` to target a
specific kubeconfig context; omit it to use the active context.

    ACM_ENABLE_LIVE_RBAC_CERTIFICATION=1 \\
    ACM_LIVE_RBAC_CONTEXT=my-disposable-hub \\
    pytest tests/test_rbac_live_certification.py -v -m live_rbac_certification

Cluster assumptions
-------------------
* The cluster must have the ACM RBAC manifests applied
  (``deploy/rbac/`` or via ``setup-rbac.sh``).
* The kubeconfig used must be the *service-account* kubeconfig generated by
  the bootstrap step, not a cluster-admin kubeconfig.
* For the decommission/finalization scenarios the optional decommission
  ClusterRole (``deploy/rbac/extensions/decommission/``) must also be bound.
* Tests are safe to run against any cluster; they make no writes.
"""

from __future__ import annotations

