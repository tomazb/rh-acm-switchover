def _check_permission(validator, api_group: str, resource: str, verb: str, namespace: str | None = None) -> None:
    """Assert a single SSAR check passes and produce a useful failure message."""
    from lib.exceptions import ValidationError

    scope = f"namespace={namespace}" if namespace else "cluster-scope"
    try:
        allowed, reason = validator.check_permission(api_group, resource, verb, namespace)
    except ValidationError as exc:
        pytest.fail(
            f"SSAR check could not be completed for "
            f"{verb} {api_group or 'core'}/{resource} ({scope}): {exc}"
        )
    assert allowed, (
        f"Permission DENIED: {verb} {api_group or 'core'}/{resource} ({scope})"
        + (f" — {reason}" if reason else "")
    )


